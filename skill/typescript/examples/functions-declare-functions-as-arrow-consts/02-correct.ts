// ----------------------------------------------------------------------------------------
// 제목 공백 정리, 검색어 비교에서 공백 차이 무시
//
// toTrimmedTitle("  초록   셔츠 ") → "초록 셔츠"
// toTrimmedTitle("초록\n셔츠") → "초록 셔츠"
// toTrimmedTitle("   ") → ""
// ----------------------------------------------------------------------------------------
// [!code ++]
export const toTrimmedTitle = (rawTitle: string): string => {
	return rawTitle.trim().replace(/\s+/g, " ");
// [!code ++]
};
